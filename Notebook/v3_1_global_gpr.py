"""## 11. Temporal Holdout Validation

Fit on 2019-2022, predict 2023. Two things get reported:

**Error metrics** — how close the point predictions are.
**95% credible-interval coverage** — what fraction of held-out observations
fall inside the model's own uncertainty bounds.

These can diverge, and the divergence is informative. Coverage near 95% with
poor RMSE means the uncertainty quantification is honest even where the means
are imprecise — a reportable result, and the difference between "bounds we
computed" and "bounds we validated".
"""

# ════════════════════════════════════════════════════════════════════════════
# CELL 11: TEMPORAL HOLDOUT — fit 2019-2022, predict 2023
# ════════════════════════════════════════════════════════════════════════════

def temporal_holdout(data, target_col, rf_selected, holdout_year=2023):
    train = data[data['year'] < holdout_year]
    test  = data[data['year'] == holdout_year]

    model = build_global_gpr(train, target_col, rf_selected, verbose=False)

    # Build test matrix with the SAME columns in the SAME order
    d = test.copy()
    trt_dummies = pd.get_dummies(d['treatment_code'], prefix='trt').astype(float)
    d = pd.concat([d, trt_dummies], axis=1)
    for c in model['trt_cols']:
        if c not in d.columns:
            d[c] = 0.0

    sub = d[model['feats'] + [target_col]].dropna()
    if len(sub) == 0:
        return None

    X_test = (sub[model['feats']].values.astype(float) - model['X_mean']) / model['X_std']
    y_true = sub[target_col].values

    log_mean, log_std = model['gpr'].predict(X_test, return_std=True)
    y_pred  = np.expm1(log_mean)
    y_lo    = np.clip(np.expm1(log_mean - 1.96 * log_std), 0, None)
    y_hi    = np.expm1(log_mean + 1.96 * log_std)

    resid = y_true - y_pred
    rmse  = np.sqrt(np.mean(resid ** 2))
    mae   = np.mean(np.abs(resid))
    bias  = np.mean(resid)
    ss_res = np.sum(resid ** 2)
    ss_tot = np.sum((y_true - y_true.mean()) ** 2)
    r2 = 1 - ss_res / ss_tot if ss_tot > 0 else np.nan
    coverage = np.mean((y_true >= y_lo) & (y_true <= y_hi))
    mean_width = np.mean(y_hi - y_lo)

    return {
        'n_train': model['n'], 'n_test': len(sub),
        'y_true': y_true, 'y_pred': y_pred, 'y_lo': y_lo, 'y_hi': y_hi,
        'rmse': rmse, 'mae': mae, 'bias': bias, 'r2': r2,
        'coverage': coverage, 'mean_ci_width': mean_width,
    }


holdout = {}
for target, model in global_models.items():
    label = model['label']
    res = temporal_holdout(gpr_input, target, top_features[target])
    holdout[target] = res
    if res is None:
        print(f'{label}: no usable holdout rows')
        continue
    print(f'\n=== {label} — temporal holdout (train 2019-2022, test 2023) ===')
    print(f'  n train / test      : {res["n_train"]} / {res["n_test"]}')
    print(f'  RMSE                : {res["rmse"]:.2f} mg/kg')
    print(f'  MAE                 : {res["mae"]:.2f} mg/kg')
    print(f'  Bias (pred - obs)   : {-res["bias"]:+.2f} mg/kg')
    print(f'  R2                  : {res["r2"]:.3f}')
    print(f'  95% CI coverage     : {res["coverage"]*100:.1f}%  (target 95%)')
    print(f'  Mean CI width       : {res["mean_ci_width"]:.1f} mg/kg')

