# ════════════════════════════════════════════════════════════════════════════

FORECAST_START = 2024
YEARS_PRED = np.arange(2019, 2029)


def predict_trajectory(model, data, treatment_code, grazing, depth_cm):
    """Query the global model across years at one experimental setting."""
    depth_num = {'0-10': 5, '10-20': 15}[depth_cm]
    graz_bin  = 1 if grazing == 'Yes' else 0

    ctx = data[(data['treatment_code'] == treatment_code) &
               (data['grazing'] == grazing) &
               (data['depth_cm'] == depth_cm)]
    if len(ctx) == 0:
        return None

    rows = []
    for yr in YEARS_PRED:
        row = {}
        for f in model['continuous']:
            if f == 'year':
                row[f] = float(yr)
            elif yr >= FORECAST_START:
                if f == 'spei':
                    row[f] = data['spei'].mean()          # observed mean
                elif f in ('co2_mean', 'ch4_mean', 'n2o_mean'):
                    v = ctx.loc[ctx['year'] == 2023, f].mean()
                    row[f] = v if not np.isnan(v) else ctx[f].mean()
                else:
                    row[f] = ctx[f].mean()
            else:
                v = ctx.loc[ctx['year'] == yr, f].mean()
                row[f] = v if not np.isnan(v) else ctx[f].mean()
        for c in model['trt_cols']:
            row[c] = 1.0 if c == f'trt_{treatment_code}' else 0.0
        row['grazing_binary'] = float(graz_bin)
        row['depth_numeric']  = float(depth_num)
        rows.append(row)

    X = pd.DataFrame(rows)[model['feats']].values.astype(float)
    if np.isnan(X).any():
        return None
    Xn = (X - model['X_mean']) / model['X_std']

    log_mean, log_std = model['gpr'].predict(Xn, return_std=True)
    return {
        'years':   YEARS_PRED,
        'mean':    np.expm1(log_mean),
        'lower':   np.clip(np.expm1(log_mean - 1.96 * log_std), 0, None),
        'upper':   np.expm1(log_mean + 1.96 * log_std),
        'obs_x':   ctx['year'].values,
        'obs_y':   ctx[model['target']].values,
    }


