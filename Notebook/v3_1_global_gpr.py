"""## 9. Global GPR Model

v3.0 filtered to one treatment x grazing x depth subset before fitting, so
those three variables had zero variance inside every model and contributed
nothing — the visible separation between panel lines came from fitting
different subsets, not from a modelled effect.

Here one model sees all rows, with treatment one-hot encoded (1/2/3 as a
number would wrongly imply Fertilized sits "between" Unfertilized and
Legume) and grazing and depth as real dimensions.
"""

# ════════════════════════════════════════════════════════════════════════════
# CELL 9: GLOBAL GPR WITH ARD KERNEL
# ════════════════════════════════════════════════════════════════════════════
from sklearn.gaussian_process.kernels import Matern, WhiteKernel, ConstantKernel

# Features that describe experimental STRUCTURE — always included as model
# dimensions, never as filters. Stripped from the RF-selected list so they
# are not added twice.
STRUCTURAL = ['treatment_code', 'depth_numeric', 'grazing_binary']


def build_global_gpr(data, target_col, rf_selected, verbose=True):
    """One GPR over all rows. Returns fitted model + scaling metadata."""
    d = data.copy()

    # One-hot treatment
    trt_dummies = pd.get_dummies(d['treatment_code'], prefix='trt').astype(float)
    d = pd.concat([d, trt_dummies], axis=1)

    continuous = [f for f in rf_selected if f not in STRUCTURAL]
    feats = continuous + list(trt_dummies.columns) + ['grazing_binary', 'depth_numeric']

    cols = list(dict.fromkeys(feats + [target_col, 'year']))
    sub = d[cols].dropna()
    X = sub[feats].values.astype(float)
    y = np.log1p(sub[target_col].values)

    X_mean = X.mean(axis=0)
    X_std  = X.std(axis=0) + 1e-8
    X_norm = (X - X_mean) / X_std

    # ARD: one length-scale per dimension. Short length-scale = the fitted
    # function varies quickly along that axis = that covariate matters.
    kernel = (ConstantKernel(1.0)
              * Matern(length_scale=np.ones(X.shape[1]), nu=1.5)
              + WhiteKernel(noise_level=0.1))

    gpr = GaussianProcessRegressor(
        kernel=kernel, n_restarts_optimizer=5,
        normalize_y=True, random_state=42
    )
    gpr.fit(X_norm, y)

    if verbose:
        print(f'  n = {len(sub)} rows, {len(feats)} dimensions')
        print(f'  features: {feats}')
        print(f'  log-marginal-likelihood: {gpr.log_marginal_likelihood_value_:.2f}')

    return {
        'gpr': gpr, 'feats': feats, 'continuous': continuous,
        'trt_cols': list(trt_dummies.columns),
        'X_mean': X_mean, 'X_std': X_std,
        'n': len(sub), 'data': sub, 'target': target_col,
    }


global_models = {}
for target, label in [('nh4_mean', 'NH\u2084\u207a'), ('no3_mean', 'NO\u2083\u207b')]:
    print(f'\n=== Fitting global GPR: {label} ===')
    global_models[target] = build_global_gpr(
        gpr_input, target, top_features[target]
    )
    global_models[target]['label'] = label

"""## 10. ARD Relevance vs RF Importance

The GP learns a separate length-scale for every input dimension. A short
length-scale means the fitted surface changes rapidly along that axis, which
is the GP's own statement about which covariates matter — arrived at by a
completely different mechanism than RF's impurity accounting.

Where the two agree, the claim is strong. Where they diverge, that gap is
itself a result worth explaining.
"""

# ════════════════════════════════════════════════════════════════════════════
# CELL 10: ARD LENGTH-SCALES vs RF IMPORTANCE
# ════════════════════════════════════════════════════════════════════════════

def ard_relevance(model):
    """Inverse length-scale, normalized to shares."""
    ls = np.atleast_1d(np.asarray(model['gpr'].kernel_.k1.k2.length_scale))
    if len(ls) != len(model['feats']):
        raise ValueError(
            f'{len(ls)} length-scales vs {len(model["feats"])} features — '
            f're-run Cell 9 to refit against the current top_features.'
        )
    rel = pd.Series(1.0 / ls, index=model['feats'])
    return (rel / rel.sum()).sort_values(ascending=False)


