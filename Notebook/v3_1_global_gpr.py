# CELL 4b: SPEI EXTRACTION FROM GRIDMET/DROUGHT
# ~4.6 km pixels — all 9 plots share one pixel, so SPEI varies by sampling
# window, not by plot. Bare point geometry: a sub-pixel buffer returns null.
# ════════════════════════════════════════════════════════════════════════════

SPEI_BANDS = ['spei30d', 'spei90d', 'spei180d']

SITE_LON = -96.43825
SITE_LAT = 41.16821


def get_spei(lon, lat, start_date, end_date):
    """Mean SPEI over the sampling window at several accumulation scales."""
    pt = ee.Geometry.Point([lon, lat])
    coll = (ee.ImageCollection('GRIDMET/DROUGHT')
              .filterBounds(pt)
              .filterDate(start_date, end_date)
              .select(SPEI_BANDS))

    n = coll.size().getInfo()
    if n == 0:
        raise ValueError(f'No GRIDMET images between {start_date} and {end_date}')

    vals = coll.mean().reduceRegion(
        reducer=ee.Reducer.mean(),
        geometry=pt,
        scale=4638
    ).getInfo()

    if all(v is None for v in vals.values()):
        raise ValueError(f'All bands null for {start_date}-{end_date}')
    return vals


spei_records = []
for year, windows in SAMPLING_WINDOWS.items():
    for (tp, start, end) in windows:
        print(f'SPEI | {year} | {tp}...', end=' ')
        try:
            vals = get_spei(SITE_LON, SITE_LAT, start, end)
            rec = {'year': year, 'time_point': tp}
            rec.update({b: vals.get(b) for b in SPEI_BANDS})
            spei_records.append(rec)
            print('OK')
        except Exception as e:
            print(f'FAILED: {e}')
            rec = {'year': year, 'time_point': tp}
            rec.update({b: None for b in SPEI_BANDS})
