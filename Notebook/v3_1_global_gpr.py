# 4 · Grazing effects — summary statistics with n, plus Holm correction
#     within the 2023 endpoint family (3 treatments × 2 analytes = 6 tests)
ge = []
for col, a in ANALYTES.items():
    for trt, tname in TRT.items():
        for yr in sorted(df['year'].unique()):
            sub = df[(df['treatment_code'] == trt) & (df['year'] == yr)]
            g = sub.loc[sub['grazing'] == 'Yes', col].dropna()
            ng = sub.loc[sub['grazing'] == 'No', col].dropna()
            if len(g) < MIN_N or len(ng) < MIN_N:
                continue
            p = stats.mannwhitneyu(g, ng, alternative='two-sided').pvalue
            ge.append(dict(analyte=a, treatment=tname, year=int(yr),
                           mean_grazed=g.mean(), sd_grazed=g.std(), n_grazed=len(g),
                           mean_ungrazed=ng.mean(), sd_ungrazed=ng.std(), n_ungrazed=len(ng),
                           diff=g.mean() - ng.mean(), p_value=p))
ge = pd.DataFrame(ge)
end = ge['year'] == 2023
pv = ge.loc[end, 'p_value'].to_numpy()
order, k, running = np.argsort(pv), len(pv), 0.0
holm = np.empty(k)
for i, idx in enumerate(order):
    running = max(running, min(1.0, (k - i) * pv[idx]))
    holm[idx] = running
ge['p_holm_2023'] = np.nan
ge.loc[end, 'p_holm_2023'] = holm
ge['sig_uncorrected'] = np.select([ge['p_value'] < 0.01, ge['p_value'] < 0.05], ['**', '*'], '')
save(ge.round(4), 'dash_grazing_effects')

