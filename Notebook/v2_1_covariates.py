"""## 7. GPR Modeling Using Top RF Features"""

def run_gpr_multifeature(data, target_col, features,
                          treatment_code, depth='0-10', grazing='No'):
    """
    GPR using top RF-selected features.
    Returns predicted mean, lower/upper CI, and observed training data.
    """
    sub = data[
        (data['treatment_code'] == treatment_code) &
        (data['depth_cm'] == depth) &
        (data['grazing'] == grazing)
    ].dropna(subset=[target_col] + features)

    if len(sub) < 3:
        print(f'  Skipping trt={treatment_code} depth={depth} grazing={grazing}: insufficient data ({len(sub)} rows)')
        return None

    X_train = sub[features].values.astype(float)
    y_raw   = sub[target_col].values
    y_train = np.log1p(y_raw)  # log transform

    # Normalize features
    X_mean = X_train.mean(axis=0)
    X_std  = X_train.std(axis=0) + 1e-8
    X_norm = (X_train - X_mean) / X_std

    kernel = Matern(nu=1.5) + WhiteKernel(noise_level=0.1)
    gpr = GaussianProcessRegressor(
        kernel=kernel,
        n_restarts_optimizer=10,
        normalize_y=True,
        random_state=42
    )
    gpr.fit(X_norm, y_train)

    # Build prediction grid: year varies 2019-2030, other features held at training mean
    years_pred = np.arange(2019, 2031)
    X_pred = np.tile(X_mean, (len(years_pred), 1))
    year_idx = features.index('year') if 'year' in features else 0
    X_pred[:, year_idx] = years_pred
    X_pred_norm = (X_pred - X_mean) / X_std

    y_log_mean, y_log_std = gpr.predict(X_pred_norm, return_std=True)

    y_mean  = np.expm1(y_log_mean)
    y_lower = np.clip(np.expm1(y_log_mean - 2*y_log_std), 0, None)
    y_upper = np.expm1(y_log_mean + 2*y_log_std)

    return {
        'years_pred': years_pred,
        'y_mean':     y_mean,
        'y_lower':    y_lower,
        'y_upper':    y_upper,
        'X_obs':      sub['year'].values,
        'y_obs':      y_raw,
    }

print('GPR function defined.')

