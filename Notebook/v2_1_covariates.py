# ── CELL D: Grazed vs Non-Grazed Statistical Comparison ──────────────────────
from scipy import stats

print('=== Grazed vs Non-Grazed: Mann-Whitney U Test ===')
print('(Non-parametric — appropriate given non-normal N distributions)\n')

summary_records = []

for target, label in [('nh4_mg_kg','NH\u2084\u207a'), ('no3_mg_kg','NO\u2083\u207b')]:
    print(f'--- {label} ---')
    for trt in TREATMENTS:
        for year in sorted(df['year'].unique()):
            sub = df[(df['treatment_code']==trt) & (df['year']==year)]
            grazed     = sub[sub['grazing']=='Yes'][target].dropna()
            not_grazed = sub[sub['grazing']=='No'][target].dropna()

            if len(grazed) < 3 or len(not_grazed) < 3:
                continue

            stat, p = stats.mannwhitneyu(grazed, not_grazed, alternative='two-sided')
            sig = '***' if p < 0.001 else '**' if p < 0.01 else '*' if p < 0.05 else 'ns'

            summary_records.append({
                'variable':       label,
                'treatment':      TREATMENT_LABELS[trt],
                'year':           year,
                'mean_grazed':    round(grazed.mean(), 2),
                'mean_not_grazed':round(not_grazed.mean(), 2),
                'diff':           round(grazed.mean() - not_grazed.mean(), 2),
                'p_value':        round(p, 4),
                'significance':   sig
            })
            print(f'  Trt {trt} | {year}: G={grazed.mean():.1f} NG={not_grazed.mean():.1f} '
                  f'diff={grazed.mean()-not_grazed.mean():+.1f} p={p:.4f} {sig}')

stats_df = pd.DataFrame(summary_records)

# Plot significance heatmap
fig, axes = plt.subplots(1, 2, figsize=(14, 5))
for ax, var in zip(axes, ['NH\u2084\u207a','NO\u2083\u207b']):
    sub = stats_df[stats_df['variable']==var].pivot(
        index='treatment', columns='year', values='diff'
    )
    p_sub = stats_df[stats_df['variable']==var].pivot(
        index='treatment', columns='year', values='p_value'
    )
    sns.heatmap(sub, ax=ax, cmap='RdBu_r', center=0, annot=True, fmt='.1f',
                linewidths=0.5, cbar_kws={'label': 'Mean diff (G - NG)'})

    # Overlay significance markers
    for i, trt in enumerate(sub.index):
        for j, yr in enumerate(sub.columns):
            try:
                p_val = p_sub.loc[trt, yr]
                sig = '***' if p_val<0.001 else '**' if p_val<0.01 else '*' if p_val<0.05 else ''
                if sig:
                    ax.text(j+0.5, i+0.8, sig, ha='center', fontsize=10, color='black')
            except:
                pass

    ax.set_title(f'{var} — Grazed minus Not Grazed (mg/kg)\n* p<0.05  ** p<0.01  *** p<0.001')
    ax.set_xlabel('Year')
    ax.set_ylabel('Treatment')

plt.suptitle('Grazing Effect on Soil N by Treatment and Year', fontweight='bold')
