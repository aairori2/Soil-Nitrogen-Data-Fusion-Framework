"""## 7. Random Forest Feature Selection
In this step, we use a Random Forest Regressor to rank the importance of our environmental covariates (NDVI, EVI) in predicting soil nitrogen levels. This addresses the 'robust data-fusion pipeline' objective by quantifying feature relevance.
"""

from sklearn.ensemble import RandomForestRegressor

# Step 14: Feature Importance Audit
def audit_feature_importance(df, target_col):
    # Prepare features: Year + GEE Indices
    features = ['year', 'ndvi', 'evi']
    sub = df.dropna(subset=[target_col] + features)

    X = sub[features]
    y = sub[target_col]

    rf = RandomForestRegressor(n_estimators=100, random_state=42)
    rf.fit(X, y)

    importance = pd.Series(rf.feature_importances_, index=features).sort_values(ascending=False)
    return importance

