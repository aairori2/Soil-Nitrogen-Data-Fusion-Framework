"""## 5. Feature-Selected GPR & Forecasts
In this stage, we integrate the **Google Earth Engine (GEE)** covariates. Based on Random Forest importance, we use **NDVI** as the primary covariate for $NO_3^-$ and **EVI** for $NH_4^+$. We generate separate forecasts for **Grazed** vs **Non-Grazed** plots to reflect management impacts.
"""

from sklearn.preprocessing import StandardScaler
from sklearn.gaussian_process import GaussianProcessRegressor
from sklearn.gaussian_process.kernels import Matern, WhiteKernel
import numpy as np

def run_gpr_refined(data, target_col, treatment_code, depth='0-10', grazing_status='No'):
    """
    Audited GPR Engine: Handles year + vegetation covariates with robust outlier management.
    """
    covariate = 'ndvi' if 'no3' in target_col else 'evi'

    # Filtering subset
    sub = data[
        (data['treatment_code'] == treatment_code) &
        (data['depth_cm'] == depth) &
        (data['grazing'] == grazing_status)
    ].dropna(subset=[target_col, covariate])

    if sub.empty or len(sub) < 3:
        return None, None, None, None, None, None

    X_train = sub[['year', covariate]].values.astype(float)

    # Calculate threshold from full dataset column to ensure stability
    global_target = data[target_col].dropna()
    threshold = global_target.quantile(0.90) if not global_target.empty else None

    # Perform robust clipping
    y_raw = sub[target_col].values
    if threshold is not None:
        y_raw = np.clip(y_raw, a_min=None, a_max=threshold)

    y_train = np.log1p(y_raw)

    scaler_X = StandardScaler()
    X_train_scaled = scaler_X.fit_transform(X_train)

    kernel = (Matern(nu=1.5, length_scale_bounds=(1e-5, 1e5)) *
              Matern(nu=1.5, length_scale_bounds=(1e-5, 1e5))) + \
             WhiteKernel(noise_level=0.1, noise_level_bounds=(1e-7, 1e2))

    gpr = GaussianProcessRegressor(kernel=kernel, n_restarts_optimizer=20, normalize_y=True, random_state=42)
    gpr.fit(X_train_scaled, y_train)

    X_pred_years = np.arange(2019, 2031).reshape(-1, 1)
    mean_cov = sub[covariate].mean()
    X_pred = np.hstack([X_pred_years, np.full((len(X_pred_years), 1), mean_cov)])

    X_pred_scaled = scaler_X.transform(X_pred)
    y_mean_log, y_std_log = gpr.predict(X_pred_scaled, return_std=True)

    return (
        X_pred_years.flatten(),
        np.expm1(y_mean_log),
        np.expm1(y_mean_log - 2 * y_std_log),
        np.expm1(y_mean_log + 2 * y_std_log),
        sub['year'].values,
        sub[target_col].values
    )

