# CELL 8b: PERMUTATION IMPORTANCE (robustness check on MDI ranking)
# ────────────────────────────────────────────────────────────────────────────
# MDI (Cell 8) is biased toward high-cardinality features — continuous
# covariates get more candidate split points than binary ones like
