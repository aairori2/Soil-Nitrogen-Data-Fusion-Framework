"""## 9. GPR Modeling Using Top RF Features"""

# ════════════════════════════════════════════════════════════════════════════
# CELL 9: GPR MODELING FUNCTION
# ════════════════════════════════════════════════════════════════════════════

def run_gpr_multifeature(data, target_col, features,
                          treatment_code, depth='0-10', grazing='No'):
    """
    Fits GPR using top RF-selected features.
    - Log-transforms target to prevent negative predictions
    - Normalizes features for numerical stability
    - Forecasts 2019-2028 (5-year projection horizon)
    - Returns mean, lower/upper CI, and observed training data
    """
    sub = data[
        (data['treatment_code'] == treatment_code) &
        (data['depth_cm']       == depth) &
        (data['grazing']        == grazing)
    ].dropna(subset=[target_col] + features)

    if len(sub) < 3:
        print(f'  Skipping trt={treatment_code} | depth={depth} | '
              f'grazing={grazing}: insufficient data ({len(sub)} rows)')
        return None

    X_train = sub[features].values.astype(float)
    y_raw   = sub[target_col].values
    y_train = np.log1p(y_raw)  # log transform — prevents negative predictions

    # Normalize features
    X_mean = X_train.mean(axis=0)
    X_std  = X_train.std(axis=0) + 1e-8
    X_norm = (X_train - X_mean) / X_std

    # Matern kernel — smooth non-linear trends + noise term
    kernel = Matern(nu=1.5) + WhiteKernel(noise_level=0.1)
    gpr = GaussianProcessRegressor(
        kernel=kernel,
        n_restarts_optimizer=10,
        normalize_y=True,
        random_state=42
    )
    gpr.fit(X_norm, y_train)

    # Forecast 2019-2028 (5-year projection beyond 2023)
    years_pred = np.arange(2019, 2029)
    X_pred = np.tile(X_mean, (len(years_pred), 1))

    # Vary year — hold all other features at training mean
    year_idx = features.index('year') if 'year' in features else 0
    X_pred[:, year_idx] = years_pred

    # For SPEI in forecast years (2024-2028) use long-term neutral value
    if 'spei' in features:
        spei_idx = features.index('spei')
        spei_forecast = 0.0  # neutral SPEI — no drought assumed
        X_pred[years_pred > 2023, spei_idx] = spei_forecast

    # For GHG in forecast years use last observed year mean
    for ghg_col in ['co2_mean', 'ch4_mean', 'n2o_mean']:
        if ghg_col in features:
            ghg_idx = features.index(ghg_col)
            last_val = sub[sub['year']==2023][ghg_col].mean()
            if np.isnan(last_val):
                last_val = sub[ghg_col].mean()
            X_pred[years_pred > 2023, ghg_idx] = last_val

    X_pred_norm = (X_pred - X_mean) / X_std
    y_log_mean, y_log_std = gpr.predict(X_pred_norm, return_std=True)

    # Back-transform from log scale
    y_mean  = np.expm1(y_log_mean)
    y_lower = np.clip(np.expm1(y_log_mean - 2*y_log_std), 0, None)
    y_upper = np.expm1(y_log_mean + 2*y_log_std)

    return {
        'years_pred': years_pred,
        'y_mean':     y_mean,
        'y_lower':    y_lower,
        'y_upper':    y_upper,
        'X_obs':      sub['year'].values,
        'y_obs':      y_raw,
    }

print('GPR function defined — forecast horizon: 2019-2028.')

