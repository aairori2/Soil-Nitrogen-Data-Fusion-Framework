def get_gee_covariates(lon, lat, start_date, end_date):
    point = ee.Geometry.Point([lon, lat]).buffer(15)
    s2 = (ee.ImageCollection('COPERNICUS/S2_SR_HARMONIZED')
            .filterBounds(point).filterDate(start_date, end_date)
            .filter(ee.Filter.lt('CLOUDY_PIXEL_PERCENTAGE', 20)).median())
    ndvi = s2.normalizedDifference(['B8','B4']).rename('NDVI')
    evi  = s2.expression(
        '2.5*((NIR-RED)/(NIR+6*RED-7.5*BLUE+1))',
        {'NIR':s2.select('B8'),'RED':s2.select('B4'),'BLUE':s2.select('B2')}
    ).rename('EVI')
    s1 = (ee.ImageCollection('COPERNICUS/S1_GRD')
            .filterBounds(point).filterDate(start_date, end_date)
            .filter(ee.Filter.eq('instrumentMode','IW'))
            .select('VV').median())
    result = (ndvi.addBands(evi).addBands(s1)
              .reduceRegion(reducer=ee.Reducer.mean(), geometry=point, scale=10))
    return result.getInfo()

